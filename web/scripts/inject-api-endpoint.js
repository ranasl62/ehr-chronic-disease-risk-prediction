#!/usr/bin/env node
/**
 * Bake API_ENDPOINT into the Angular production build (optional).
 *
 * - Unset / empty → BUILD_API_ENDPOINT = '' (same-origin / nginx / ng serve proxy)
 * - Set → absolute API base, e.g. https://ehr-api.larucare.com
 *   (hosted UI at https://ehr-risk-framework.larucare.com should set CORS_ORIGINS to that origin)
 *
 * Used by: npm run build, web/Dockerfile (ARG/ENV), Vercel/Render build env.
 */
const fs = require('fs');
const path = require('path');

const out = path.join(__dirname, '../src/environments/api-endpoint.generated.ts');
const raw = (process.env.API_ENDPOINT || process.env.NG_APP_API_ENDPOINT || '').trim();
const endpoint = raw.replace(/\/+$/, '');

const contents = `/* Generated by scripts/inject-api-endpoint.js — do not edit by hand. */
export const BUILD_API_ENDPOINT = ${JSON.stringify(endpoint)};
`;

fs.writeFileSync(out, contents, 'utf8');
console.log(
  endpoint
    ? `[inject-api-endpoint] BUILD_API_ENDPOINT=${endpoint}`
    : '[inject-api-endpoint] BUILD_API_ENDPOINT="" (same-origin / proxy)',
);
